const { chromium } = require('playwright-core');
const path = require('path'), os = require('os');
const EXE = path.join(os.homedir(), "Library/Caches/ms-playwright/chromium-1248/chrome-mac-arm64/Google Chrome for Testing.app/Contents/MacOS/Google Chrome for Testing");
(async () => {
  const b = await chromium.launch({ executablePath: EXE, args: ['--use-gl=angle','--use-angle=metal','--enable-gpu'] });
  const ctx = await b.newContext({ viewport:{width:390,height:844}, deviceScaleFactor:3, isMobile:true, hasTouch:true });
  const pg = await ctx.newPage();
  pg.on('pageerror', e=>console.log('[err]',String(e).slice(0,160)));
  await pg.goto('http://127.0.0.1:8899/?ui&mobile', { waitUntil:'load', timeout:180000 });
  await pg.waitForFunction(()=>window.MP&&window.XM_TOUR, null, {timeout:180000});
  await pg.waitForTimeout(10000);
  console.log('before stopDirector:', JSON.stringify(await pg.evaluate(()=>(window.XM&&window.XM.cam)?window.XM.cam():{cam:[window.XM_TOUR.camera.position.x,window.XM_TOUR.camera.position.y,window.XM_TOUR.camera.position.z],introOn:window.XM_TOUR.intro.active,introT:window.XM_TOUR.intro.t})));
  await pg.evaluate(()=>{document.querySelectorAll('#mp-login,#mp-mask,#boot').forEach(e=>e.style.display='none'); if(window.__fp)window.__fp.on=false; window.XM_TOUR.stopDirector();});
  await pg.waitForTimeout(500);
  await pg.evaluate(()=>window.MP.freezeCam(0,2.2,2,0,3.2,8));
  await pg.waitForTimeout(500);
  console.log('after freeze 0.5s:', JSON.stringify(await pg.evaluate(()=>(window.XM&&window.XM.cam)?window.XM.cam():{cam:[window.XM_TOUR.camera.position.x,window.XM_TOUR.camera.position.y,window.XM_TOUR.camera.position.z],introOn:window.XM_TOUR.intro.active,introT:window.XM_TOUR.intro.t})));
  await pg.waitForTimeout(2500);
  console.log('after freeze 3s:', JSON.stringify(await pg.evaluate(()=>(window.XM&&window.XM.cam)?window.XM.cam():{cam:[window.XM_TOUR.camera.position.x,window.XM_TOUR.camera.position.y,window.XM_TOUR.camera.position.z],introOn:window.XM_TOUR.intro.active,introT:window.XM_TOUR.intro.t})));
  console.log('dir:', JSON.stringify(await pg.evaluate(()=>({active:window.XM_TOUR.director.active, shot:window.XM_TOUR.director.shot&&window.XM_TOUR.director.shot.id}))));
  await b.close();
})();
